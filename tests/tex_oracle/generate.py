#!/usr/bin/env python3
"""Measures the formulas in cases.tsv with LuaLaTeX and writes golden.tsv and glyphs.tsv.

TeX is the reference: the test `tex_oracle` (tests/tex_oracle.rs) lays out the MathML of each case
(mathml.tsv) and compares it with these measurements, so running the test needs no TeX.

- golden.tsv: the width, height and depth of each formula.
- glyphs.tsv: the position of every glyph of each formula, from the box LuaTeX typesets (the Lua
  code that walks the box is glyphs.lua): glyph index in the font, x from the left edge of the
  box, y up from the baseline.

Run this when the LaTeX of a case in cases.tsv changes, or for a new case (which also needs a row
in mathml.tsv):

    python3 tests/tex_oracle/generate.py

Needs lualatex with unicode-math and amsmath. Typesets with the font the Rust tests use
(tests/testfiles/latinmodern-math.otf) at 10pt, so 1pt = 100 font units.
"""
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
FONT = HERE.parent / "testfiles" / "latinmodern-math.otf"
SP_PER_UNIT = 65536 / 100  # 1 unit = 1/1000 em = 0.01pt at 10pt/em

cases = []
for line in (HERE / "cases.tsv").read_text(encoding="utf-8").splitlines():
    if line.strip() and not line.startswith("#"):
        name, mode, latex = line.split("\t")
        assert mode in ("d", "t") and re.fullmatch(r"[a-z0-9-]+", name), line
        cases.append((name, mode, latex))


def measure_with_tex():
    body = []
    for name, mode, latex in cases:
        style = r"\displaystyle " if mode == "d" else ""
        body.append(
            rf"\setbox0\hbox{{${style}{latex}$}}"
            rf"\typeout{{ORACLE {name} \number\wd0 \space\number\ht0 \space\number\dp0}}"
            rf'\directlua{{dump_glyphs("{name}")}}'
        )

    tex = "\n".join([
        r"\documentclass[10pt]{article}",
        r"\usepackage{amsmath}",
        r"\usepackage{unicode-math}",
        rf"\setmathfont{{{FONT.name}}}[Path={FONT.parent}/]",
        # \mathrm and the names of operators such as \sin are set in the text font, Latin Modern
        # Roman, unless told otherwise. It has no MATH table (no italic corrections, no top accent
        # attachments), and formel draws upright letters with the math font: use that.
        r"\setoperatorfont\symup",
        rf'\directlua{{dofile("{HERE / "glyphs.lua"}")}}',
        r"\begin{document}",
        r"\renewcommand\mathrm[1]{\symup{#1}}",
        *body,
        r"\end{document}",
    ])

    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "oracle.tex").write_text(tex, encoding="utf-8")
        # no line breaks in the output: the results are read from it
        env = {**os.environ, "max_print_line": "10000", "error_line": "254", "half_error_line": "238"}
        run = subprocess.run(
            ["lualatex", "-interaction=nonstopmode", "-halt-on-error", "oracle.tex"],
            cwd=tmp, capture_output=True, text=True, env=env,
        )
        log = run.stdout
        if run.returncode != 0:
            sys.exit(log[-3000:])
    version = subprocess.run(["luatex", "--version"], capture_output=True, text=True).stdout.splitlines()[0]

    measured = {}
    for m in re.finditer(r"ORACLE (\S+) (-?\d+) (-?\d+) (-?\d+)", log):
        measured[m[1]] = [int(m[i]) / SP_PER_UNIT for i in (2, 3, 4)]
    missing = [n for n, _, _ in cases if n not in measured]
    if missing:
        sys.exit(f"no result for: {missing}")

    out = [
        f"# Generated by generate.py with {version} and {FONT.name}. Do not edit.",
        "# name\tmode\twidth\theight\tdepth   (font units, 1000 per em; height and depth measured from the baseline)",
    ]
    out += [f"{n}\t{mode}\t" + "\t".join(f"{v:.1f}" for v in measured[n]) for n, mode, _ in cases]
    (HERE / "golden.tsv").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {len(cases)} cases to golden.tsv")

    glyphs = {n: [] for n, _, _ in cases}
    for m in re.finditer(r"GLYPH\t(\S+)\t(-?\d+)\t(\d+)\t(-?\d+)\t(-?\d+)", log):
        glyphs[m[1]].append((int(m[2]), int(m[4]) / SP_PER_UNIT, int(m[5]) / SP_PER_UNIT))
    out = [
        f"# Generated by generate.py with {version} and {FONT.name}. Do not edit.",
        "# name\tglyph index\tx\ty   (font units; x from the left edge of the box, y up from the baseline)",
    ]
    for name, mode, _ in cases:
        for index, x, y in glyphs[name]:
            assert index >= 0, f"{name}: a glyph without an index in the font"
            out.append(f"{name}\t{index}\t{x:.1f}\t{y:.1f}")
    (HERE / "glyphs.tsv").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {sum(map(len, glyphs.values()))} glyphs to glyphs.tsv")


measure_with_tex()
