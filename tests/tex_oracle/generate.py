#!/usr/bin/env python3
"""Writes the two files the test `tex_oracle` (tests/tex_oracle.rs) compares: for the formulas in
cases.tsv (LaTeX, the source of every case),

- golden.tsv: what LuaLaTeX makes of each, the reference. Needs lualatex with unicode-math and
  amsmath. Typesets with the font the Rust tests use (tests/testfiles/latinmodern-math.otf) at
  10pt, so 1pt = 100 font units.
- mathml.tsv: the MathML of each, from the same converter as the web app (the example
  `oracle_mathml` of formel-wasm). The test lays this MathML out; the converter itself is not
  part of it. Needs cargo.

Run it when cases.tsv changes, or to refresh one file:

    python3 tests/tex_oracle/generate.py [tex] [mathml]
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FONT = HERE.parent / "testfiles" / "latinmodern-math.otf"
SP_PER_UNIT = 65536 / 100  # 1 unit = 1/1000 em = 0.01pt at 10pt/em

cases = []
for line in (HERE / "cases.tsv").read_text(encoding="utf-8").splitlines():
    if line.strip() and not line.startswith("#"):
        name, mode, latex = line.split("\t")
        assert mode in ("d", "t") and re.fullmatch(r"[a-z0-9-]+", name), line
        cases.append((name, mode, latex))


def measure_with_tex():
    body = []
    for name, mode, latex in cases:
        style = r"\displaystyle " if mode == "d" else ""
        body.append(
            rf"\setbox0\hbox{{${style}{latex}$}}"
            rf"\typeout{{ORACLE {name} \number\wd0 \space\number\ht0 \space\number\dp0}}"
        )

    tex = "\n".join([
        r"\documentclass[10pt]{article}",
        r"\usepackage{amsmath}",
        r"\usepackage{unicode-math}",
        rf"\setmathfont{{{FONT.name}}}[Path={FONT.parent}/]",
        # TeX puts 1.2pt of "null delimiter space" around every fraction and \left. / \right. .
        # MathML has no such thing, so measure without it.
        r"\nulldelimiterspace=0pt",
        r"\begin{document}",
        *body,
        r"\end{document}",
    ])

    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "oracle.tex").write_text(tex, encoding="utf-8")
        run = subprocess.run(
            ["lualatex", "-interaction=nonstopmode", "-halt-on-error", "oracle.tex"],
            cwd=tmp, capture_output=True, text=True,
        )
        log = run.stdout
        if run.returncode != 0:
            sys.exit(log[-3000:])
    version = subprocess.run(["luatex", "--version"], capture_output=True, text=True).stdout.splitlines()[0]

    measured = {}
    for m in re.finditer(r"ORACLE (\S+) (-?\d+) (-?\d+) (-?\d+)", log):
        measured[m[1]] = [int(m[i]) / SP_PER_UNIT for i in (2, 3, 4)]
    missing = [n for n, _, _ in cases if n not in measured]
    if missing:
        sys.exit(f"no result for: {missing}")

    out = [
        f"# Generated by generate.py with {version} and {FONT.name}. Do not edit.",
        "# name\tmode\twidth\theight\tdepth   (font units, 1000 per em; height and depth measured from the baseline)",
    ]
    out += [f"{n}\t{mode}\t" + "\t".join(f"{v:.1f}" for v in measured[n]) for n, mode, _ in cases]
    (HERE / "golden.tsv").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {len(cases)} cases to golden.tsv")


def convert_to_mathml():
    run = subprocess.run(
        ["cargo", "run", "-q", "-p", "formel-wasm", "--example", "oracle_mathml", "--", str(HERE / "cases.tsv")],
        cwd=ROOT, capture_output=True, text=True,
    )
    if run.returncode != 0:
        sys.exit(run.stderr[-3000:])
    out = [
        "# Generated by generate.py with the LaTeX to MathML converter of formel-wasm. Do not edit.",
        "# name\tMathML",
    ]
    out += run.stdout.splitlines()
    names = [line.split("\t")[0] for line in run.stdout.splitlines()]
    assert names == [n for n, _, _ in cases], "the converter skipped or reordered cases"
    (HERE / "mathml.tsv").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {len(cases)} cases to mathml.tsv")


steps = sys.argv[1:] or ["tex", "mathml"]
if not set(steps) <= {"tex", "mathml"}:
    sys.exit(__doc__)
if "tex" in steps:
    measure_with_tex()
if "mathml" in steps:
    convert_to_mathml()
