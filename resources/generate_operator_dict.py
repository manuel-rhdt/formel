#!/usr/bin/env python3
"""Regenerates the operator dictionary of src/mathmlparser/operator_dict.rs.

The table is MathML Core's (https://www.w3.org/TR/mathml-core/#operator-dictionary), taken from
tables/operator-dictionary.html of https://github.com/w3c/mathml-core, kept next to this script
in operator-dictionary.html. To update it, download that file again and run

    python3 resources/generate_operator_dict.py

Standard library only. Only the region between the BEGIN and END GENERATED markers of the Rust file
is replaced. What is taken from the table, per (character, form):

- lspace and rspace, in 1/18 em (every value in the table is a multiple of that),
- the properties fence, separator, stretchy, symmetric, largeop and movablelimits.

Not taken: the stretch axis (the engine decides from the element the operator is in), and nothing
for characters that have no entry: they get the default spacing of 5/18 em at lookup.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLE = HERE / "operator-dictionary.html"
RUST = HERE.parent / "src" / "mathmlparser" / "operator_dict.rs"
SOURCE = "https://github.com/w3c/mathml-core/blob/66256baa0e7125171ff16b3831acfba3c43179c7/tables/operator-dictionary.html"

FLAGS = {
    "symmetric": "SYMMETRIC",
    "fence": "FENCE",
    "stretchy": "STRETCHY",
    "separator": "SEPARATOR",
    "largeop": "LARGEOP",
    "movablelimits": "MOVABLE_LIMITS",
}
FORMS = {"prefix": "Prefix", "infix": "Infix", "postfix": "Postfix"}

def eighteenths(cell: str, what: str) -> int:
    value = re.fullmatch(r"([0-9.]+)(em)?", re.sub(r"<.*?>", "", cell).strip())
    assert value, f"{what}: unexpected spacing {cell!r}"
    units = float(value[1]) * 18
    assert abs(units - round(units)) < 1e-6, f"{what}: {cell!r} is not a multiple of 1/18 em"
    return round(units)

entries = {}
for row in re.findall(r"<tr>(.*?)</tr>", TABLE.read_text(encoding="utf-8"), re.S):
    cells = re.findall(r"<td>(.*?)</td>", row, re.S)
    if not cells:
        continue  # the header
    assert len(cells) == 6, row
    assert cells[0].count("U+") == 1, f"a key of more than one character: {cells[0]!r}"
    codepoint = int(re.search(r"U\+([0-9A-F]+)", cells[0])[1], 16)
    form = re.search(r"<code>(\w+)</code>", cells[2])[1]
    what = f"U+{codepoint:04X} {form}"
    props = re.sub(r"<.*?>", "", cells[5]).replace("N/A", "").split()
    unknown = [p for p in props if p not in FLAGS]
    assert not unknown, f"{what}: unknown properties {unknown}"
    key = (codepoint, list(FORMS).index(form))
    assert key not in entries, f"{what} twice"
    entries[key] = (eighteenths(cells[3], what), eighteenths(cells[4], what), sorted(props))

lines = []
for (codepoint, form), (lspace, rspace, props) in sorted(entries.items()):
    flags = " | ".join(FLAGS[p] for p in props) or "0"
    lines.append(
        f"    _Entry {{ character: '\\u{{{codepoint:X}}}', form: Form::{list(FORMS.values())[form]}, "
        f"lspace: {lspace}, rspace: {rspace}, flags: {flags} }},"
    )

table = "\n".join([
    f"// BEGIN GENERATED by resources/generate_operator_dict.py from {SOURCE}",
    "// Do not edit: change the generator or the table and run it again.",
    "#[cfg_attr(rustfmt, rustfmt_skip)]",
    f"pub static DICTIONARY: [_Entry<u8>; {len(lines)}] = [",
    *lines,
    "];",
    "// END GENERATED",
])

source = RUST.read_text(encoding="utf-8")
begin = source.find("// BEGIN GENERATED")
end = source.find("// END GENERATED")
if begin < 0 or end < begin:
    sys.exit(f"{RUST} has no BEGIN/END GENERATED markers")
end += len("// END GENERATED")
RUST.write_text(source[:begin] + table + source[end:], encoding="utf-8")
print(f"wrote {len(lines)} entries to {RUST.relative_to(HERE.parent)}")
